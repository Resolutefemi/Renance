#!/usr/bin/env python3
"""
gen_learn_catalog.py — generates the HARDCODED course catalog for the
Renance web app (founder directive 2026-10-14: "make sure the courses
list are hard coded and make sure it's working just like supreme").

Outputs:
  1. apps/web/lib/learn-catalog-secondary.ts
     — the 50 JAMB/WAEC/NECO subject roadmaps (id, title, topic count)
       inlined in the client bundle: the Course tab renders INSTANTLY,
       no API round-trip, exactly like the Supreme reference site.
  2. apps/web/public/learn/tertiary-catalog.json
     — the full 10,606-course tertiary tree (id, title, faculty,
       institution type, topic count) as a lazy-fetched static asset:
       same data the API serves, but un-deletable by a backend outage.

The ids are byte-identical to internal/learn/curriculum.go's seed
(SEC-<BODY>-<SUBJECT> for secondary, the CSV's CRS ids for tertiary),
so a hardcoded course opens the SAME backend path as a catalog row.
"""
import csv
import glob
import gzip
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
API = os.path.join(ROOT, "apps", "study-api")
WEB = os.path.join(ROOT, "apps", "web")

# ─── 1. Secondary: the subject roadmaps ──────────────────────────────────
subjects = {"jamb": [], "waec": [], "neco": []}
for path in sorted(glob.glob(os.path.join(API, "internal", "learn", "seed", "secondary", "*.json"))):
    with open(path) as fh:
        s = json.load(fh)
    body = s["body"].lower()
    subjects[body].append({
        "id": f"SEC-{body.upper()}-{s['subject'].upper()}",
        "title": s["title"],
        "n": len(s["topics"]),
    })

lines = [
    "'use client';",
    "",
    "/**",
    " * HARDCODED secondary catalog (founder directive 2026-10-14: \"make",
    " * sure the courses list are hard coded and make sure it's working",
    " * just like supreme\"). Generated by scripts/gen_learn_catalog.py",
    " * from the study-api's seed/secondary roadmaps — the ids match the",
    " * backend seed byte for byte, so a tap opens the real path.",
    " */",
    "",
    "export interface HardCatalogItem {",
    "  id: string;",
    "  title: string;",
    "  /** Topic count, shown on the row. */",
    "  n: number;",
    "}",
    "",
]
for body in ("jamb", "waec", "neco"):
    rows = subjects[body]
    lines.append(f"export const {body.upper()}_CATALOG: HardCatalogItem[] = [")
    for r in sorted(rows, key=lambda x: x["title"]):
        lines.append(f'  {{ id: {json.dumps(r["id"])}, title: {json.dumps(r["title"])}, n: {r["n"]} }},')
    lines.append("];")
    lines.append("")

lines.append("""/** The secondary desk's hardcoded shelf, JAMB first (the default). */
export function secondaryCatalog(body: string): HardCatalogItem[] {
  switch (body) {
    case 'waec': return WAEC_CATALOG;
    case 'neco': return NECO_CATALOG;
    default: return JAMB_CATALOG;
  }
}
""")

out_ts = os.path.join(WEB, "lib", "learn-catalog-secondary.ts")
with open(out_ts, "w") as fh:
    fh.write("\n".join(lines))
print(f"wrote {out_ts} ({sum(len(v) for v in subjects.values())} subjects)")

# ─── 2. Tertiary: the full course tree as a static asset ────────────────
courses = []
with gzip.open(os.path.join(API, "internal", "learn", "seed", "05_Courses_Master.csv.gz"), "rt") as fh:
    rows = list(csv.reader(fh))
for r in rows[2:]:
    if len(r) > 7 and r[1].strip().startswith("CRS-"):
        courses.append({
            "i": r[1],                    # course id (CRS-…)
            "t": r[7],                    # title
            "f": r[5],                    # faculty
            "y": r[4],                    # institution type
        })

# Topic counts from 06_Course_Topics.csv.gz
counts: dict[str, int] = {}
with gzip.open(os.path.join(API, "internal", "learn", "seed", "06_Course_Topics.csv.gz"), "rt") as fh:
    trows = list(csv.reader(fh))
for r in trows[2:]:
    if len(r) > 2 and r[1].startswith("TOP-") and r[2].startswith("CRS-"):
        counts[r[2]] = counts.get(r[2], 0) + 1
for c in courses:
    c["n"] = counts.get(c["i"], 0)

os.makedirs(os.path.join(WEB, "public", "learn"), exist_ok=True)
out_json = os.path.join(WEB, "public", "learn", "tertiary-catalog.json")
with open(out_json, "w") as fh:
    json.dump({"v": 1, "courses": courses}, fh, separators=(",", ":"))
size = os.path.getsize(out_json)
print(f"wrote {out_json} ({len(courses)} courses, {size/1024:.0f} KB raw)")
