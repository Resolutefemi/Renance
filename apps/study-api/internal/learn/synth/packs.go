package synth

// packs.go: discipline knowledge packs 1 to 10. A pack is the domain
// brain for one broad field: the lexicons fill every sentence and
// question slot, the unit arc gives the course its 15 unit ladder and
// calcKind selects the worked example generators. Everything is
// hyphen free by construction; Clean() guards the rest.

import "strings"

type pack struct {
        key       string   // pack id
        keywords  []string // routing keywords (course title, dept, faculty)
        calc      string   // "" or math | physics | chem | stats | econ | cs | eng
        nouns     []string // core domain entities
        processes []string // methods and actions
        tools     []string // instruments, materials, software
        laws      []string // named principles and laws
        contexts  []string // application contexts
        siblings  []string // sibling concepts (distractors, cross links)
        issues    []string // field challenges
        careers   []string // where graduates work
        metrics   []string // quantities the field measures
        units     []string // the 15 unit arc
}

